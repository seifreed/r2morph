.intel_syntax noprefix
.global _start
.text

_start:
    movdqa xmm0, xmmword ptr [rip + byte_left]
    vpsubsb xmm0, xmm0, xmmword ptr [rip + byte_right]
    movd eax, xmm0
    movdqa xmm1, xmmword ptr [rip + word_left]
    vpsubsw xmm1, xmm1, xmmword ptr [rip + word_right]
    movd ecx, xmm1
    and eax, 0x7f
    and ecx, 0x7f
    add eax, ecx
    and eax, 0x7f
    mov edi, eax
    mov eax, 60
    syscall

.section .rodata
.p2align 4
byte_left:
    .byte 0x7f, 0x80, 0x0a, 0xf6, 0x01, 0xff, 0x20, 0xe0
    .byte 0x40, 0xc0, 0x7e, 0x82, 0x11, 0xef, 0x33, 0xdd
byte_right:
    .byte 0x01, 0xff, 0x14, 0xec, 0x02, 0x01, 0x40, 0x20
    .byte 0x7f, 0x80, 0x7f, 0x80, 0x10, 0xf0, 0x30, 0xd0
word_left:
    .word 0x7fff, 0x8000, 0x0010, 0xfff0, 0x0100, 0xff00, 0x2222, 0xdddd
word_right:
    .word 0xffff, 0x0001, 0x0020, 0xffe0, 0x0200, 0x0100, 0x1111, 0xeeee
